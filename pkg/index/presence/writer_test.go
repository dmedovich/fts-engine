type sourceFunc func(func(segment.TermPostings) error) error

func (s sourceFunc) ExportSegmentTerms(yield func(segment.TermPostings) error) error { return s(yield) }

type writerFunc func([]byte) (int, error)

func (w writerFunc) Write(p []byte) (int, error) { return w(p) }

func TestStreamingWrite(t *testing.T) {
	s := benchmarkSource()
	s = append(s, segment.TermPostings{Term: "singleton", Postings: postings(math.MaxUint32)})
	var buf bytes.Buffer
	if err := WriteFromSource(context.Background(), &buf, s); err != nil {
		t.Fatal(err)
	}
	r, err := Open(buf.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	for _, tp := range s {
		got := collect(t, r, []string{tp.Term}, nil)
		want := make([]fts.DocOrd, len(tp.Postings))
		for i, p := range tp.Postings {
			want[i] = p.Ord
		}
		if !slices.Equal(got, want) {
			t.Fatalf("roundtrip %q", tp.Term)
		}
	}
	// The callback's posting storage may be reused immediately after it returns.
	reused := sourceFunc(func(yield func(segment.TermPostings) error) error {
		p := postings(0, 1, math.MaxUint32)
		if err := yield(segment.TermPostings{Term: "a", Postings: p}); err != nil {
			return err
		}
		p[0].Ord, p[1].Ord, p[2].Ord = 2, 3, 4
		return yield(segment.TermPostings{Term: "b", Postings: p})
	})
	blob, err := BuildFromSource(reused)
	if err != nil {
		t.Fatal(err)
	}
	r, err = Open(blob)
	if err != nil {
		t.Fatal(err)
	}
	if got := collect(t, r, []string{"a"}, nil); !slices.Equal(got, []fts.DocOrd{0, 1, math.MaxUint32}) {
		t.Fatal(got)
	}
}

// Generated by the original FPR1 writer before the streaming refactor. Keep
// this fixture stable: it covers singleton extremes and three delta blocks.
func TestFPR1Compatibility(t *testing.T) {
	want, err := os.ReadFile("testdata/fpr1-legacy.bin")
	if err != nil {
		t.Fatal(err)
	}
	p := make([]fts.Posting, 300)
	for i := range p {
		p[i] = fts.Posting{Ord: fts.DocOrd(i * 1000000), Count: 1}
	}
	got, err := BuildFromSource(source{{Term: "z", Postings: postings(math.MaxUint32)}, {Term: "a", Postings: p}, {Term: "zero", Postings: postings(0)}})
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("FPR1 encoding changed")
	}
	r, err := Open(want)
	if err != nil {
		t.Fatal(err)
	}
	if got := collect(t, r, []string{"a"}, nil); len(got) != 300 || got[299] != 299000000 {
		t.Fatal(got)
	}
}

func TestStreamingWriteFailures(t *testing.T) {
	sentinel := errors.New("write failed")
	s := benchmarkSource()
	// Fail at the initial flush, in postings, in the dictionary and in the footer.
	blob, err := BuildFromSource(s)
	if err != nil {
		t.Fatal(err)
	}
	for _, limit := range []int{0, 40000, len(blob) - footerSize - 1, len(blob) - 1} {
		left := limit
		w := writerFunc(func(p []byte) (int, error) {
			n := min(left, len(p))
			left -= n
			if n < len(p) {
				return n, sentinel
			}
			return n, nil
		})
		if err := WriteFromSource(context.Background(), w, s); !errors.Is(err, sentinel) {
			t.Fatalf("limit %d: %v", limit, err)
		}
	}
	short := writerFunc(func(p []byte) (int, error) { return len(p) - 1, nil })
	if err := WriteFromSource(context.Background(), short, s); !errors.Is(err, io.ErrShortWrite) {
		t.Fatal(err)
	}
	if err := WriteFromSource(context.Background(), io.Discard, sourceFunc(func(func(segment.TermPostings) error) error { return sentinel })); !errors.Is(err, sentinel) {
		t.Fatal(err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	w := writerFunc(func(p []byte) (int, error) {
		cancel()
		return len(p), nil
	})
	if err := WriteFromSource(ctx, w, s); !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	if err := WriteFromSource(ctx, io.Discard, s); !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
}

func TestLazyMetadataAndReadAhead(t *testing.T) {
	blob, err := BuildFromSource(benchmarkSource())
	if err != nil {
		t.Fatal(err)
	}
	backing := &countedReader{Reader: bytes.NewReader(blob)}
	r, err := OpenReaderAt(backing, int64(len(blob)))
	if err != nil {
		t.Fatal(err)
	}
	backing.calls, backing.read = 0, 0
	collect(t, r, []string{"common", "missing"}, nil)
	if backing.calls != 0 {
		t.Fatal("missing term read postings")
	}
	table, err := fts.NewOrdinalTable([]uint64{10, 20})
	if err != nil {
		t.Fatal(err)
	}
	c, n, err := table.Candidates(context.Background(), []uint64{11, 19})
	if err != nil {
		t.Fatal(err)
	}
	if err := fts.IntersectTermsWithIterator(context.Background(), r, []string{"common"}, c, n, func(fts.DocOrd) bool {
		t.Fatal("unexpected match")
		return true
	}); err != nil {
		t.Fatal(err)
	}
	if backing.calls != 0 {
		t.Fatal("empty candidate stream read postings")
	}
	got := collect(t, r, []string{"common"}, nil)
	if len(got) != 100000 {
		t.Fatal(len(got))
	}
	if backing.calls > 10 {
		t.Fatalf("sequential traversal made %d reads", backing.calls)
	}
	if backing.read > 120000 {
		t.Fatalf("sequential traversal read %d bytes", backing.read)
	}
	// Cross read-ahead windows and alternate sequential access with long jumps.
	c, _, err = r.OpenPostings(context.Background(), "common")
	if err != nil {
		t.Fatal(err)
	}
	defer c.Close()
	for _, ord := range []fts.DocOrd{0, 128, 130, 40000, 40128, 99999} {
		if !c.Advance(ord) || c.Ord() != ord {
			t.Fatalf("advance %d: %d %v", ord, c.Ord(), c.Err())
		}
		if ord < 99999 && (!c.Next() || c.Ord() != ord+1) {
			t.Fatal(c.Err())
		}
	}
	if c.Next() || c.Err() != nil {
		t.Fatal(c.Err())
	}
}
